
-- Attendance Registry
-- Migration V2: Create course enrollments.
--
-- Business rules:
-- BR-02: Only users with the STUDENT role can enroll.
-- BR-03: A student cannot enroll twice in the same course.
--
-- Database: PostgreSQL

-- =====================================================
-- 1. Create enrollments table
-- =====================================================

CREATE TABLE enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    enrollment_date DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT fk_enrollments_student
        FOREIGN KEY (student_id)
        REFERENCES users(id),

    CONSTRAINT fk_enrollments_course
        FOREIGN KEY (course_id)
        REFERENCES courses(id),

    CONSTRAINT uk_enrollments_student_course
        UNIQUE (student_id, course_id)
);

-- =====================================================
-- 2. Create indexes
-- =====================================================

CREATE INDEX idx_enrollments_course_id
    ON enrollments(course_id);

-- The unique constraint already creates an index
-- covering student_id and course_id.

-- =====================================================
-- 3. BR-02: Validate student role on enrollment
-- =====================================================

CREATE OR REPLACE FUNCTION validate_enrollment_student()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM users
        WHERE id = NEW.student_id
          AND role = 'STUDENT'
        FOR UPDATE
    ) THEN
        RAISE EXCEPTION
            'Enrollment requires a user with STUDENT role';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validate_enrollment_student
BEFORE INSERT OR UPDATE OF student_id
ON enrollments
FOR EACH ROW
EXECUTE FUNCTION validate_enrollment_student();

-- =====================================================
-- 4. BR-02: Prevent invalid role changes
-- =====================================================

CREATE OR REPLACE FUNCTION prevent_enrolled_student_role_change()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.role = 'STUDENT'
       AND NEW.role <> 'STUDENT'
       AND EXISTS (
           SELECT 1
           FROM enrollments
           WHERE student_id = OLD.id
       )
    THEN
        RAISE EXCEPTION
            'Cannot change role: user has active enrollments';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_prevent_enrolled_student_role_change
BEFORE UPDATE OF role
ON users
FOR EACH ROW
EXECUTE FUNCTION prevent_enrolled_student_role_change();

