
-- Attendance Registry
-- Migration V3: Create class sessions.
-- Database: PostgreSQL

CREATE TABLE class_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    start_at TIMESTAMP NOT NULL,
    end_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_class_sessions_course
        FOREIGN KEY (course_id)
        REFERENCES courses(id),

    CONSTRAINT ck_class_sessions_title_not_blank
        CHECK (LENGTH(TRIM(title)) > 0),

    CONSTRAINT ck_class_sessions_valid_time
        CHECK (end_at > start_at)
);

CREATE INDEX idx_class_sessions_course_id
    ON class_sessions(course_id);

CREATE INDEX idx_class_sessions_start_at
    ON class_sessions(start_at);
