
-- Attendance Registry
-- Migration V4: Create QR codes.
-- Database: PostgreSQL

CREATE TABLE qr_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    token VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_qr_codes_session
        FOREIGN KEY (session_id)
        REFERENCES class_sessions(id),

    CONSTRAINT uq_qr_codes_token
        UNIQUE (token),

    CONSTRAINT ck_qr_codes_valid_expiration
        CHECK (expires_at > created_at),

    CONSTRAINT ck_qr_codes_token_not_blank
        CHECK (LENGTH(TRIM(token)) > 0)
);

CREATE INDEX idx_qr_codes_session_id
    ON qr_codes(session_id);

CREATE INDEX idx_qr_codes_expires_at
    ON qr_codes(expires_at);
