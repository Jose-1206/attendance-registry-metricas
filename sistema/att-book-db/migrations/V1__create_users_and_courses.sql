
-- Attendance Registry
-- Migration V1: Create users and courses tables.
-- Compatible with the current Spring Boot JPA entities.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,

    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('STUDENT', 'TEACHER'))
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    code VARCHAR(30) NOT NULL,
    teacher_id BIGINT NOT NULL,

    CONSTRAINT fk_courses_teacher
        FOREIGN KEY (teacher_id)
        REFERENCES users(id),

    CONSTRAINT ck_courses_code_not_blank
        CHECK (LENGTH(TRIM(code)) > 0)
);

CREATE INDEX idx_courses_teacher_id
    ON courses(teacher_id);
